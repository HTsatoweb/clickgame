function bonus(){
  var c=0, p=0, n=0;
  for (var id in owned){
    if (!owned[id]) continue;
    var el = DB[id|0];
    if (!el) continue;
    n++; c += el.bC; p += el.bP;
  }
  return {c:c,p:p,n:n};
}

function tryUnlock(){
  var cc=clicks(), en=energyNum(), changed=0;
  for (var i=0;i<DB.length;i++){
    if (owned[i]) continue;
    var el=DB[i];
    if (cc>=el.reqC && en>=el.reqE){ owned[i]=1; changed++; }
    else if (i>cc+20) break; // later ones need more clicks; skip far ahead a bit
  }
  if (changed) save();
  return changed;
}

